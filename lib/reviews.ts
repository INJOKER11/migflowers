export const REVIEW_FILTERS = ['Усі', '5 зірок', '4 зірки', 'Найновіші'] as const;
export type ReviewFilter = (typeof REVIEW_FILTERS)[number];

export function filterReviews(filter: ReviewFilter): Review[] {
  if (filter === '5 зірок') return REVIEWS.filter((r) => r.rating === 5);
  if (filter === '4 зірки') return REVIEWS.filter((r) => r.rating === 4);
  return REVIEWS;
}

export function stars(rating: number): string {
  return '★'.repeat(rating);
}

