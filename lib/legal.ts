export const LEGAL: Record<Locale, Record<LegalDoc, LegalDocument>> = { uk, ru };

/** The document ids are the same in both locales — they are the URL. */
export const LEGAL_DOCS: LegalDoc[] = ['privacy', 'terms', 'returns'];

const SELLER_LABELS: Record<Locale, { h: string; address: string; phone: string }> = {
  uk: { h: 'Продавець', address: 'Адреса', phone: 'Телефон' },
  ru: { h: 'Продавец', address: 'Адрес', phone: 'Телефон' },
};

export function getLegal(doc: string, locale: Locale): LegalDocument | undefined {
  if (!(LEGAL_DOCS as string[]).includes(doc)) return undefined;
  const document = LEGAL[locale][doc as LegalDoc];
  if (doc === 'privacy') return document;

  /* Terms and returns name the party the customer contracts with — what
     LiqPay's monitoring looks for. Last, so the opening paragraph still
     makes the page's description. */
  const s = seller();
  const l = SELLER_LABELS[locale];
  return {
    ...document,
    sections: [
      ...document.sections,
      {
        h: l.h,
        p: `${s.name}, РНОКПП ${s.taxId}. ${l.address}: ${s.address}. ${l.phone}: ${s.phone}.`,
      },
    ],
  };
}
