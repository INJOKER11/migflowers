export const LEGAL: Record<Locale, Record<LegalDoc, LegalDocument>> = { uk, ru };

/** The document ids are the same in both locales — they are the URL. */
export const LEGAL_DOCS: LegalDoc[] = ['privacy', 'terms'];

export function getLegal(doc: string, locale: Locale): LegalDocument | undefined {
  return doc === 'privacy' || doc === 'terms' ? LEGAL[locale][doc] : undefined;
}
